export function isPointInPolygon(
  lat: number,
  lon: number,
  polygon: [number, number][]
): boolean {
  let inside = false
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const [yi, xi] = polygon[i]
    const [yj, xj] = polygon[j]
    if (
      yi > lon !== yj > lon &&
      lat < ((xj - xi) * (lon - yi)) / (yj - yi) + xi
    ) {
      inside = !inside
    }
  }
  return inside
}

export function isOnLand(lat: number, lon: number): boolean {
  for (const polygon of continentPolygons) {
    if (isPointInPolygon(lat, lon, polygon.points)) {
      return true
    }
  }
  return false
}

export function generateContinentDots(
  targetCount: number = 5000
): { lat: number; lon: number; brightness: number }[] {
  const dots: { lat: number; lon: number; brightness: number }[] = []
  const goldenRatio = (1 + Math.sqrt(5)) / 2

  const overshoot = targetCount * 3
  for (let i = 0; i < overshoot && dots.length < targetCount; i++) {
    const theta = (2 * Math.PI * i) / goldenRatio
    const phi = Math.acos(1 - (2 * (i + 0.5)) / overshoot)

    const lat = (phi * 180) / Math.PI - 90
    const lon = ((theta * 180) / Math.PI) % 360
    const lonNorm = lon > 180 ? lon - 360 : lon

    if (lat < -80 || lat > 80) continue

    if (isOnLand(lat, lon)) {
      const brightness = 0.85 + Math.random() * 0.1
      dots.push({ lat, lon: lonNorm, brightness })
    }
  }

  return dots
}
